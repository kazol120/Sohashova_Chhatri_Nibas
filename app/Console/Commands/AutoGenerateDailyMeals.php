<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use App\Models\User;
use App\Models\Backend\Meal;
use App\Models\Backend\RoomBookingHistory;
use Carbon\Carbon;

class AutoGenerateDailyMeals extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'meals:generate-daily';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Auto generate daily meal entries for all active residents unless turned off';

    /**
     * Execute the console command.
     */
    public function handle()
    {
        $today = Carbon::today()->format('Y-m-d');
        $this->info("Generating daily meals for date: {$today}");

        $users = User::all();
        $mealService = app(\App\Services\MealService::class);
        $mealService->ensureAutoMealGeneratedForUsers($users, $today);

        $this->info("Auto-generated daily meals successfully synced.");
        return 0;
    }
}
